/**
 * Нормализация текста: нижний регистр, удаление пунктуации и лишних пробелов
 */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\wа-яё\s+\-*/().]/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Проверка, является ли ввод математическим выражением
 */
function isMathExpression(text: string): boolean {
  // Паттерн: цифры, операторы, скобки, пробелы, точки
  const mathPattern = /^[\d\s+\-*/().,%^]+$/;
  const normalized = text.trim();
  return mathPattern.test(normalized) && /\d/.test(normalized) && /[+\-*/^%]/.test(normalized);
}

/**
 * Безопасное вычисление математического выражения (без eval)
 */
function safeCalculate(expr: string): string {
  try {
    // Заменяем ^ на ** для возведения в степень
    let sanitized = expr.replace(/\^/g, '**');
    // Убираем всё кроме допустимых символов
    sanitized = sanitized.replace(/[^0-9+\-*/().%\s]/g, '');
    
    if (!sanitized.trim()) return 'Не удалось распознать выражение';
    
    // Проверяем на подозрительные конструкции
    if (/[a-zA-Z]/.test(sanitized)) return 'Выражение содержит недопустимые символы';
    
    // Используем Function для безопасного вычисления (не eval!)
    // Создаём изолированную функцию без доступа к переменным
    const result = new Function(`"use strict"; return (${sanitized})`)();
    
    if (typeof result !== 'number' || !isFinite(result)) {
      return 'Не удалось вычислить (возможно, деление на ноль?)';
    }
    
    // Округляем до 10 знаков после запятой
    const rounded = Math.round(result * 1e10) / 1e10;
    return `🧮 ${expr.trim()} = **${rounded}**`;
  } catch {
    return 'Не удалось вычислить выражение. Проверь синтаксис!';
  }
}

/**
 * Основной метод получения ответа от офлайн-бота
 */
export function getOfflineResponse(userMessage: string): string {
  const normalized = normalize(userMessage);
  
  if (!normalized) {
    return 'Напиши что-нибудь, я жду! 😊';
  }
  
  // Проверяем, является ли ввод математическим выражением
  if (isMathExpression(userMessage)) {
    return safeCalculate(userMessage);
  }
  
  // Ищем совпадения в базе знаний
  let bestMatch: { keys: string[]; response: string | (() => string) } | null = null;
  let bestScore = 0;
  
  for (const entry of knowledgeBase) {
    for (const key of entry.keys) {
      const normalizedKey = normalize(key);
      
      // Точное совпадение — максимальный приоритет
      if (normalized === normalizedKey) {
        bestMatch = entry;
        bestScore = 100;
        break;
      }
      
      // Содержит ключевое слово
      if (normalized.includes(normalizedKey)) {
        const score = normalizedKey.length; // Чем длиннее ключ — тем точнее
        if (score > bestScore) {
          bestScore = score;
          bestMatch = entry;
        }
      }
      
      // Ключевое слово содержит нормализованный ввод (для коротких фраз)
      if (normalizedKey.includes(normalized) && normalized.length > 2) {
        const score = normalized.length;
        if (score > bestScore) {
          bestScore = score;
          bestMatch = entry;
        }
      }
    }
    if (bestScore >= 100) break;
  }
  
  if (bestMatch) {
    if (typeof bestMatch.response === 'function') {
      return bestMatch.response();
    }
    return bestMatch.response;
  }
  
  // Если ничего не нашли
  const fallbacks = [
    'Хм, не совсем понял. Попробуй переформулировать? 🤔',
    'Интересный вопрос! Но в офлайн-режиме я не знаю ответа. Попробуй режим API! 💡',
    'Не уверен, что правильно понял. Можешь спросить по-другому? 😅',
    'Пока не знаю, как на это ответить. Но я учусь! Спроси что-нибудь другое 🙃',
  ];
  
  return fallbacks[Math.floor(Math.random() * fallbacks.length)];
}
